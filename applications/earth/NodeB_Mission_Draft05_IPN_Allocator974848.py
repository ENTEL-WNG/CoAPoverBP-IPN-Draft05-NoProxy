# CoAP-over-BP v4 implementation uses:
# 1 byte V/TT/TKL + 1 byte Code + 3 byte Message ID
COAP_HEADER_SIZE = 5

# Use the Payload-length option defined by the local aiocoap fork.
PAYLOAD_LENGTH_OPTION = int(OptionNumber.PAYLOAD_LENGTH)

# CoAP-over-BP v4 uses a 24-bit Message ID.
# Node B keeps its own Message ID sequence for NON responses.
MAX_MID = 16777215

# File used to remember Node B's next response MID
# even if NodeBaap2.py is restarted.
MID_STATE_FILE = str(Path.home() / 'coapbp/experiments/draft05-ipn/state/earth_response_mid_state.json')

response_current_id = 1


def save_mid_state():
    """Save Node B's next response MID to disk."""

    state = {
        'next_mid': response_current_id
    }

    Path(MID_STATE_FILE).parent.mkdir(parents=True, exist_ok=True)
    with open(MID_STATE_FILE, 'w') as f:
        json.dump(state, f)


def load_mid_state():
    """Load Node B's next response MID from disk."""

    global response_current_id

    try:
        with open(MID_STATE_FILE, 'r') as f:
            state = json.load(f)

        saved_mid = state.get('next_mid', 1)

        if 1 <= saved_mid <= MAX_MID:
            response_current_id = saved_mid

            print(
                f"Loaded Node B MID state: "
                f"next response MID={response_current_id}"
            )

        else:
            print(
                "Invalid saved MID state. "
                "Starting response MID from 1."
            )

            response_current_id = 1

    except FileNotFoundError:

        print(
            "No Node B MID state file found. "
            "Starting response MID from 1."
        )

        response_current_id = 1

    except (json.JSONDecodeError, TypeError, ValueError):

        print(
            "Could not read Node B MID state. "
            "Starting response MID from 1."
        )

        response_current_id = 1


def next_response_mid():
    """Return the next 24-bit Message ID generated by Node B."""

    global response_current_id

    mid = response_current_id

    response_current_id = (
        response_current_id % MAX_MID
    ) + 1

    # Save the NEXT MID so it survives a program restart.
    save_mid_state()

    return mid


# Load the saved MID state once when Node B starts.
load_mid_state()


resources = {}


def save_resources_to_file():
    """Persist resource values to disk."""

    data_to_save = {
        name: resource_obj.data
        for name, resource_obj in resources.items()
    }

    Path(DATABASE_FILE).parent.mkdir(parents=True, exist_ok=True)
    with open(DATABASE_FILE, 'w') as f:
        json.dump(data_to_save, f)

    print("Database saved to", DATABASE_FILE)


def load_resources_from_file():
    """Load persisted resource values if available."""

    if not os.path.exists(DATABASE_FILE):
        print("No database file found, starting fresh.")
        return

    with open(DATABASE_FILE, 'r') as f:
        loaded_data = json.load(f)

    for name, data in loaded_data.items():
        resources[name] = DynamicResource(
            initial_data=data
        )

    print("Database loaded from", DATABASE_FILE)


class DynamicResource(resource.Resource):
    """A resource supporting GET, PUT, and DELETE methods."""

    def __init__(self, initial_data=None):

        super().__init__()

        if initial_data is None:
            initial_data = {
                'values': []
            }

        self.data = initial_data


    async def render_get(self, request):

        payload = str(
            self.data['values']
        ).encode('utf-8')

        return aiocoap.Message(
            code=aiocoap.CONTENT,
            payload=payload
        )


    async def render_put(self, request):

        try:

            value = request.payload.decode(
                'utf-8'
            )

            self.data['values'].append(
                value
            )

            save_resources_to_file()

            return aiocoap.Message(
                code=aiocoap.CHANGED,
                payload=b"Value appended."
            )

        except Exception as e:

            print(
                "PUT error:",
                e
            )

            return aiocoap.Message(
                code=aiocoap.BAD_REQUEST,
                payload=b"Invalid PUT payload."
            )


    async def render_delete(self, request):

        self.data['values'].clear()

        save_resources_to_file()

        return aiocoap.Message(
            code=aiocoap.DELETED,
            payload=b"Resource values cleared."
        )


async def handle_post(request):
    """Handle POST requests to create new resources."""

    try:

        name = request.payload.decode(
            'utf-8'
        ).strip()

        if not name:

            return aiocoap.Message(
                code=aiocoap.BAD_REQUEST,
                payload=b"Missing resource name."
            )

        if name in resources:

            return aiocoap.Message(
                code=aiocoap.BAD_REQUEST,
                payload=b"Resource already exists."
            )

        resources[name] = DynamicResource()

        save_resources_to_file()

        print(
            f"Created new resource: /{name}"
        )

        return aiocoap.Message(
            code=aiocoap.CREATED,
            payload=f"Created {name}".encode('utf-8')
        )

    except Exception as e:

        print(
            "POST error:",
            e
        )

        return aiocoap.Message(
            code=aiocoap.BAD_REQUEST,
            payload=b"Invalid POST payload."
        )


def decode_extended_option_value(
    data,
    position,
    nibble
):
    """
    Decode the extended CoAP option
    delta or option length.
    """

    if nibble < 13:

        return nibble, position


    if nibble == 13:

        if position >= len(data):

            raise ValueError(
                "Truncated CoAP option extension"
            )

        return (
            13 + data[position],
            position + 1
        )


    if nibble == 14:

        if position + 2 > len(data):

            raise ValueError(
                "Truncated CoAP option extension"
            )

        value = int.from_bytes(
            data[position:position + 2],
            byteorder='big'
        )

        return (
            269 + value,
            position + 2
        )


    raise ValueError(
        "Illegal CoAP option nibble value 15"
    )


def find_payload_length_option(
    data,
    start_offset
):
    """
    Look for Payload-length in the CoAP
    message beginning at start_offset.

    Returns:

        (None, None)

    if Payload-length is absent.

    Otherwise returns:

        (payload_length, option_end)
    """

    if (
        start_offset + COAP_HEADER_SIZE
        > len(data)
    ):

        raise ValueError(
            "Truncated CoAP header"
        )


    token_length = (
        data[start_offset] & 0x0F
    )


    if token_length > 8:

        raise ValueError(
            "Invalid CoAP Token length"
        )


    position = (
        start_offset
        + COAP_HEADER_SIZE
        + token_length
    )


    if position > len(data):

        raise ValueError(
            "Truncated CoAP Token"
        )


    current_option_number = 0


    while position < len(data):

        option_header = data[position]


        # Payload marker reached.
        # Therefore Payload-length was not present.
        if option_header == 0xFF:

            return None, None


        position += 1


        delta_nibble = (
            option_header >> 4
        )

        length_nibble = (
            option_header & 0x0F
        )


        option_delta, position = (
            decode_extended_option_value(
                data,
                position,
                delta_nibble
            )
        )


        option_length, position = (
            decode_extended_option_value(
                data,
                position,
                length_nibble
            )
        )


        current_option_number += (
            option_delta
        )


        option_end = (
            position
            + option_length
        )


        if option_end > len(data):

            raise ValueError(
                "Truncated CoAP option value"
            )


        if (
            current_option_number
            == PAYLOAD_LENGTH_OPTION
        ):

            option_value = data[
                position:option_end
            ]


            # An empty uint encoding represents zero.
            if option_value:

                payload_length = int.from_bytes(
                    option_value,
                    byteorder='big'
                )

            else:

                payload_length = 0


            return (
                payload_length,
                option_end
            )


        position = option_end


    return None, None


def extract_aggregate_member(
    data,
    start_offset
):
    """
    Extract one CoAP message from an Aggregate.

    Payload-length is used to calculate
    the end of this Aggregate member.
    """

    payload_length, option_end = (
        find_payload_length_option(
            data,
            start_offset
        )
    )


    if payload_length is None:

        raise ValueError(
            "Missing Payload-length "
            "option in Aggregate member"
        )


    # ---------------------------------------------------------
    # Zero-length CoAP payload
    # ---------------------------------------------------------

    if payload_length == 0:

        message_end = option_end


    # ---------------------------------------------------------
    # Non-zero CoAP payload
    # ---------------------------------------------------------

    else:

        if (
            option_end >= len(data)
            or data[option_end] != 0xFF
        ):

            raise ValueError(
                "Payload marker (0xFF) "
                "not found after Payload-length"
            )


        payload_start = (
            option_end + 1
        )


        message_end = (
            payload_start
            + payload_length
        )


        if message_end > len(data):

            raise ValueError(
                "Payload-length exceeds "
                "remaining Aggregate bytes"
            )


    return (
        data[start_offset:message_end],
        message_end
    )


async def process_request(
    request,
    send_client,
    request_source_eid
):
    """
    Process one decoded CoAP request
    and send one CoAP response.
    """

    if request_source_eid not in ('ipn:974848.1.10', 'ipn:974848.1.11'):
        print('Unexpected request source:', request_source_eid)
        return
    path = request.opt.uri_path

    resource_name = (
        path[0]
        if path
        else ''
    )

    resource_path = (
        "/" + "/".join(path)
        if path
        else "/"
    )

    print()
    print("=" * 60)
    print("INCOMING CoAP-over-BP REQUEST")
    print("=" * 60)

    print(
        f"Request Source EID       : "
        f"{request_source_eid}"
    )

    print(
        "Request Destination EID  : "
        "ipn:974848.3.64"
    )

    print(
        f"CoAP Method              : "
        f"{request.code}"
    )

    print(
        f"Requested Resource       : "
        f"{resource_path}"
    )

    print(
        f"Message ID               : "
        f"{request.mid}"
    )

    print(
        f"Token                    : "
        f"{request.token.hex()}"
    )


    # Mars mission paths take precedence over the legacy dynamic database.
    # The data is simulated; the BP/CoAP exchange is real.
    if (resource_path == '/mission/safety-guidance' and request.code == aiocoap.GET
            and request_source_eid == 'ipn:974848.1.10'):
        response = aiocoap.Message(
            code=aiocoap.CONTENT,
            payload=(b'SOL 42 DUST STORM WARNING: secure instruments; '
                     b'reduce rover movement; await updated guidance.'),
        )

    elif (resource_path == '/science/observations' and request.code == aiocoap.POST
          and request_source_eid == 'ipn:974848.1.11'):
        try:
            observation = json.loads(request.payload.decode('utf-8'))
            if not isinstance(observation, dict) or observation.get('sol') != 42:
                raise ValueError('Expected simulated Sol 42 observation object')
            Path(MISSION_LOG_FILE).parent.mkdir(parents=True, exist_ok=True)
            with open(MISSION_LOG_FILE, 'a', encoding='utf-8') as fout:
                fout.write(json.dumps({'source_eid': request_source_eid,
                                       'observation': observation}) + '\n')
            response = aiocoap.Message(
                code=aiocoap.CREATED,
                payload=b'Sol 42 science observations stored on Earth.',
            )
        except (ValueError, UnicodeDecodeError) as exc:
            response = aiocoap.Message(
                code=aiocoap.BAD_REQUEST,
                payload=('Invalid science data: ' + str(exc)).encode('utf-8'),
            )

    elif resource_path in ('/mission/safety-guidance', '/science/observations'):
        response = aiocoap.Message(code=aiocoap.METHOD_NOT_ALLOWED,
                                   payload=b'Method not allowed for mission resource')

    elif resource_name in resources:

        resource_obj = resources[
            resource_name
        ]


        if request.code == aiocoap.PUT:

            handler = getattr(
                resource_obj,
                'render_put',
                None
            )


        elif request.code == aiocoap.GET:

            handler = getattr(
                resource_obj,
                'render_get',
                None
            )


        elif request.code == aiocoap.DELETE:

            handler = getattr(
                resource_obj,
                'render_delete',
                None
            )


        else:

            handler = None


        if handler:

            try:

                response = await handler(
                    request
                )

            except Exception as e:

                print(
                    "Error during resource handling:",
                    e
                )

                response = aiocoap.Message(
                    code=aiocoap.INTERNAL_SERVER_ERROR,
                    payload=b"Internal server error"
                )


        else:

            response = aiocoap.Message(
                code=aiocoap.METHOD_NOT_ALLOWED,
                payload=b"Method not allowed"
            )


    else:

        if request.code == aiocoap.POST:

            response = await handle_post(
                request
            )

        else:

            response = aiocoap.Message(
                code=aiocoap.NOT_FOUND,
                payload=b"Resource not found"
            )


    # Match the response to the request using the Token.
    response.token = request.token


    if request.mtype == Type.NON:

        # A response to a NON request is a separate NON message.
        # Node B therefore generates its own 24-bit Message ID.
        response.mtype = Type.NON

        response.mid = next_response_mid()


    else:

        # Piggybacked response to a CON request.
        # The ACK uses the same Message ID as the CON request.
        response.mtype = Type.ACK

        response.mid = request.mid


    # Response is currently sent as one Single CoAP message.
    payload = response.encode()


    # Draft v4:
    # This implementation currently uses NON CoAP traffic.
    # A bundle carrying one Single NON CoAP message uses NON_LIFETIME.
    NON_LIFETIME_SECONDS = 100

    bundle_lifetime_ms = (
        NON_LIFETIME_SECONDS * 1000
    )


    print()

    print(
        "OUTGOING CoAP-over-BP RESPONSE"
    )

    print("-" * 60)

    print(
        "Responding Application   : "
        "Earth CoAP Server (NodeB_Mission_Draft04.py)"
    )

    print(
        "Earth CoAP Endpoint      : "
        "ipn:974848.3.64"
    )

    print(
        f"Response Destination EID : "
        f"{request_source_eid}"
    )

    print(
        f"CoAP Response Code       : "
        f"{response.code}"
    )

    print(
        f"Resource                 : "
        f"{resource_path}"
    )

    print("=" * 60)


    # send_adu_rpc() sends the response ADU and also receives
    # uD3TN's AAPResponse, allowing us to verify the lifetime
    # actually reported for the created BP bundle.
    aap_response = await send_client.send_adu_rpc(

        make_bundle_adu(request_source_eid, len(payload), bundle_lifetime_ms),

        payload,
    )


    print(
        f"Earth sent Single NON response, "
        f"Requested BP lifetime: "
        f"{bundle_lifetime_ms} ms "
        f"({bundle_lifetime_ms / 1000:.0f} s)"
    )


    if aap_response.HasField(
        "bundle_headers"
    ):

        actual_lifetime_ms = (
            aap_response.bundle_headers.lifetime_ms
        )


        print(
            f"uD3TN reported BP lifetime: "
            f"{actual_lifetime_ms} ms "
            f"({actual_lifetime_ms / 1000:.0f} s)"
        )


        if (
            actual_lifetime_ms
            == bundle_lifetime_ms
        ):

            print(
                "Earth response lifetime "
                "verification: PASS"
            )

        else:

            print(
                "Earth response lifetime "
                "verification: FAIL"
            )


    else:

        print(
            "Earth response lifetime "
            "verification: UNVERIFIED "
            "(no bundle headers returned by uD3TN)"
        )


def make_bundle_adu(destination, length, lifetime):
    fields = aap2_pb2.BundleADU.DESCRIPTOR.fields_by_name
    args = {'dst_eid': destination, 'payload_length': length}
    if 'lifetime_ms' in fields:
        args['lifetime_ms'] = lifetime
    else:
        print('WARNING: AAP2 BundleADU lacks lifetime_ms; '
              'BP lifetime request not applied')
    return aap2_pb2.BundleADU(**args)


send_client = AAP2AsyncUnixClient(
    SERVER_ADDRESS
)


receive_client = AAP2AsyncUnixClient(
    SERVER_ADDRESS
)


async def main():
    """Load resources and start CoAP-over-BP handler."""

    load_resources_from_file()


    async with send_client, receive_client:

        # Both AAP2 connections belong to the same
        # CoAP-over-BP application endpoint:
        # dtn://b.dtn/coap
        #
        # send_client is used to SEND bundles.
        # receive_client is used to RECEIVE bundles.
        # The shared secret allows both connections
        # to use the same AAP2 agent ID.

        secret = await send_client.configure(
            agent_id='64'
        )


        await receive_client.configure(
            agent_id='64',
            subscribe=True,
            secret=secret
        )


        await bundle_coap_server(
            receive_client,
            send_client
        )


async def bundle_coap_server(
    receive_client,
    send_client
):
    """
    Receive BP ADUs and distinguish between:

    Single:
        Payload-length absent.

    Aggregate:
        Payload-length present.
    """

    try:

        while True:

            adu_msg, recv_payload = (
                await receive_client.receive_adu()
            )


            print(
                f"Received ADU from "
                f"{adu_msg.src_eid}: "
                f"{len(recv_payload)} bytes"
            )


            await receive_client.send_response_status(
                aap2_pb2.ResponseStatus.RESPONSE_STATUS_SUCCESS
            )


            try:

                first_payload_length, _ = (
                    find_payload_length_option(
                        recv_payload,
                        0
                    )
                )


                # =====================================================
                # SINGLE
                # =====================================================

                if first_payload_length is None:

                    request = Message.decode(
                        recv_payload
                    )


                    print(
                        "Parsed Single CoAP request: "
                        f"MID={request.mid} "
                        f"Token={request.token.hex()} "
                        f"Code={request.code}"
                    )


                    await process_request(
                        request,
                        send_client,
                        adu_msg.src_eid
                    )


                # =====================================================
                # AGGREGATE
                # =====================================================

                else:

                    offset = 0

                    message_number = 1


                    while offset < len(
                        recv_payload
                    ):

                        (
                            coap_bytes,
                            next_offset
                        ) = extract_aggregate_member(
                            recv_payload,
                            offset
                        )


                        request = Message.decode(
                            coap_bytes
                        )


                        print(
                            "Parsed Aggregate member "
                            f"#{message_number}: "
                            f"MID={request.mid} "
                            f"Token={request.token.hex()} "
                            f"Code={request.code} "
                            f"Payload-length="
                            f"{request.opt.payload_length}"
                        )


                        await process_request(
                            request,
                            send_client,
                            adu_msg.src_eid
                        )


                        offset = next_offset

                        message_number += 1


            except Exception as e:

                print(
                    "Failed to parse CoAP message:",
                    e
                )


    finally:

        await receive_client.disconnect()

        await send_client.disconnect()


if __name__ == "__main__":

    asyncio.run(
        main()
    )
